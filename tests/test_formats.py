import json

import pytest

from terimce import formats


def write(tmp_path, name, text):
    p = tmp_path / name
    p.write_text(text, encoding="utf-8")
    return p


def test_po_basic_multiline_context_and_plural(tmp_path):
    p = write(tmp_path, "tr.po", '''msgid ""
msgstr ""
"Language: tr\\n"

#: menu.c:1
msgctxt "menu"
msgid "Start"
msgstr "Başla"

msgid ""
"Line one\\n"
"line two"
msgstr "Bir\\nİki"

msgid "%d apple"
msgid_plural "%d apples"
msgstr[0] "%d elma"
msgstr[1] "%d elma"
msgid "Quoted \\"x\\""
msgstr "Tırnaklı \\"x\\""
''')
    entries = formats.read(p)
    assert [(e.key, e.source, e.target) for e in entries] == [
        ("menu", "Start", "Başla"),
        ("Line one\nline two", "Line one\nline two", "Bir\nİki"),
        ("%d apple", "%d apple", "%d elma"),
        ("%d apple", "%d apples", "%d elma"),
        ('Quoted "x"', 'Quoted "x"', 'Tırnaklı "x"'),
    ]
    assert entries[0].line == 6


def test_po_broken_line_reports_position(tmp_path):
    p = write(tmp_path, "tr.po", 'msgid "a"\nmsgstr oops\n')
    with pytest.raises(formats.FormatError, match=":2:"):
        formats.read(p)


def test_csv_detects_columns_and_key(tmp_path):
    p = write(tmp_path, "t.csv", 'id,EN,TR\nmenu.start,Start,Başla\n"x","a, b","c, d"\n')
    entries = formats.read(p)
    assert [(e.key, e.source, e.target, e.line) for e in entries] == [
        ("menu.start", "Start", "Başla", 2),
        ("x", "a, b", "c, d", 3),
    ]


def test_csv_explicit_columns_and_tsv(tmp_path):
    p = write(tmp_path, "t.tsv", "orig\tceviri\nHi\tSelam\n")
    entries = formats.read(p, source_col="orig", target_col="1")
    assert [(e.source, e.target) for e in entries] == [("Hi", "Selam")]
    with pytest.raises(formats.FormatError, match="source"):
        formats.read(p)


def test_json_pair_flattens_and_matches_keys(tmp_path):
    src = write(tmp_path, "en.json", json.dumps({"menu": {"start": "Start", "quit": "Quit"},
                                                 "tips": ["Jump", "Run"]}))
    tgt = write(tmp_path, "tr.json", json.dumps({"menu": {"start": "Başla"},
                                                 "tips": ["Zıpla"], "extra": "x"},
                                                ensure_ascii=False))
    entries = formats.read(tgt, source=src)
    assert [(e.key, e.source, e.target) for e in entries] == [
        ("menu.start", "Start", "Başla"),
        ("tips[0]", "Jump", "Zıpla"),
    ]


def test_json_needs_source(tmp_path):
    with pytest.raises(formats.FormatError, match="--source"):
        formats.read(write(tmp_path, "tr.json", "{}"))


def test_xunity(tmp_path):
    p = write(tmp_path, "_AutoGeneratedTranslations.txt",
              "// yorum\nStart=Başla\na\\=b=a\\=b çeviri\n\nbozuk satır\n")
    entries = formats.read(p)
    assert [(e.source, e.target, e.line) for e in entries] == [
        ("Start", "Başla", 2),
        ("a=b", "a=b çeviri", 3),
    ]


def test_bom_is_ignored(tmp_path):
    p = tmp_path / "t.csv"
    p.write_bytes("﻿source,target\nA,B\n".encode("utf-8"))
    assert formats.read(p)[0].source == "A"


def test_unknown_extension(tmp_path):
    with pytest.raises(formats.FormatError, match="--format"):
        formats.read(write(tmp_path, "a.xyz", ""))
